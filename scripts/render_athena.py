"""Write the Athena SQL files from the schemas and sql/gold/ (no AWS calls).

    sql/athena/01_silver_tables.sql   databases, external tables with partition projection, latest-record views
    sql/athena/02_gold_ctas.sql       CREATE TABLE AS SELECT for every gold table

Usage (from the repo root, venv active):
    python scripts/render_athena.py                          # placeholder bucket name
    python scripts/render_athena.py --bucket my-curated-bucket
"""

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from analytics.catalog import BUCKET_PLACEHOLDER, athena_silver_ddl  # noqa: E402
from analytics.gold import athena_ctas, load_gold_queries  # noqa: E402

HEADER = """-- Generated by scripts/render_athena.py. Do not edit by hand: change the schemas or sql/gold/ and re-run.
-- Athena runs one statement at a time; statements are separated by a line containing only ";".
-- Bucket: {bucket}
"""


def write(path: Path, bucket: str, statements: list[str]) -> None:
    body = "\n;\n\n".join(statements) + "\n;\n"
    path.write_text(HEADER.format(bucket=bucket) + "\n" + body, encoding="utf-8")
    print(f"Wrote {path.relative_to(REPO)} ({len(statements)} statements)")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bucket", default=BUCKET_PLACEHOLDER, help="curated bucket name")
    bucket = ap.parse_args().bucket

    out = REPO / "sql" / "athena"
    out.mkdir(parents=True, exist_ok=True)
    write(out / "01_silver_tables.sql", bucket, athena_silver_ddl(bucket))
    write(out / "02_gold_ctas.sql", bucket,
          [stmt for q in load_gold_queries() for stmt in athena_ctas(q, bucket)])
    return 0


if __name__ == "__main__":
    sys.exit(main())
